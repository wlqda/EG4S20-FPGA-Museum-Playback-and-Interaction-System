// Two-flop synchronizer plus 20 ms stable-level filtering at 25 MHz.
module museum_slide_switch #(parameter STABLE_CYCLES=500000)(
 input clk,rst,switch_in,output reg enabled);
 (* async_reg="true" *) reg [1:0] sync;
 reg [18:0] count;
 always @(posedge clk)begin
  if(rst)begin sync<=0;enabled<=0;count<=0;end
  else begin
   sync<={sync[0],switch_in};
   if(sync[1]==enabled)count<=0;
   else if(count==STABLE_CYCLES-1)begin enabled<=sync[1];count<=0;end
   else count<=count+1'b1;
  end
 end
endmodule
